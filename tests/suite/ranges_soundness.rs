/// A deterministic pseudo-random stream, so the generated functions are the
/// same on every run.
struct Stream(u64);

impl Stream {
    fn next(&mut self) -> u64 {
        self.0 = self
            .0
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        self.0.wrapping_shr(33)
    }

    fn below(&mut self, bound: usize) -> usize {
        usize::try_from(self.next())
            .ok()
            .and_then(|value| value.checked_rem(bound))
            .unwrap_or(0)
    }

    fn chance(&mut self, one_in: usize) -> bool {
        self.below(one_in) == 0
    }

    fn pick<T: Copy>(&mut self, items: &[T]) -> Option<T> {
        let index = self.below(items.len());
        items.get(index).copied()
    }
}

/// The byte types the generated inputs have.
const BYTES: [MockType; 2] = [MockType::I8, MockType::U8];

/// Every integer type a conversion may produce.
const INTEGERS: [MockType; 8] = [
    MockType::I8,
    MockType::U8,
    MockType::I16,
    MockType::U16,
    MockType::I32,
    MockType::U32,
    MockType::I64,
    MockType::U64,
];

/// Constants near the edges an 8-bit value has.
const VALUES: [i128; 16] = [
    0, 1, 2, 3, 7, 8, 9, 0x40, 0x7F, 0x80, 0x81, 0xC8, 0xFE, 0xFF, -1, -128,
];

/// Shift counts either side of every width.
const COUNTS: [i128; 11] = [0, 1, 3, 7, 8, 9, 15, 16, 31, 33, 63];

/// The type of the same width with the other signedness.
fn flipped(ty: MockType) -> MockType {
    match ty {
        MockType::I8 => MockType::U8,
        MockType::U8 => MockType::I8,
        MockType::I16 => MockType::U16,
        MockType::U16 => MockType::I16,
        MockType::I32 => MockType::U32,
        MockType::U32 => MockType::I32,
        MockType::I64 => MockType::U64,
        MockType::U64 => MockType::I64,
        other => other,
    }
}

/// `value` as a constant of type `ty`.
fn constant_of(ty: MockType, value: i128) -> Option<ConstValue<MockTarget>> {
    let signed = |width| wrap(value, (width, true));
    let unsigned = |width| wrap(value, (width, false));
    Some(match ty {
        MockType::I8 => ConstValue::I8(i8::try_from(signed(8)).ok()?),
        MockType::U8 => ConstValue::U8(u8::try_from(unsigned(8)).ok()?),
        MockType::I16 => ConstValue::I16(i16::try_from(signed(16)).ok()?),
        MockType::U16 => ConstValue::U16(u16::try_from(unsigned(16)).ok()?),
        MockType::I32 => ConstValue::I32(i32::try_from(signed(32)).ok()?),
        MockType::U32 => ConstValue::U32(u32::try_from(unsigned(32)).ok()?),
        MockType::I64 => ConstValue::I64(i64::try_from(signed(64)).ok()?),
        MockType::U64 => ConstValue::U64(u64::try_from(unsigned(64)).ok()?),
        _ => return None,
    })
}

/// Builds one generated function at a time.
struct Generator {
    stream: Stream,
    builder: Builder,
    /// Values defined so far that a later operation may read, with their types.
    scope: Vec<(SsaVarId, MockType)>,
}

impl Generator {
    /// A constant of `ty`, written sometimes through a constant of the other
    /// signedness - `U8(200)` into a signed byte is how a lift spells `-56`.
    fn constant(&mut self, block: usize, ty: MockType, pool: &[i128]) -> Option<SsaVarId> {
        let value = self.stream.pick(pool)?;
        let spelled = if self.stream.chance(3) {
            flipped(ty)
        } else {
            ty
        };
        let constant = constant_of(spelled, value)?;
        Some(self.builder.constant(block, ty, constant))
    }

    /// Another in-scope value of `ty`'s width, or a fresh constant of `ty`.
    fn operand(&mut self, block: usize, ty: MockType) -> Option<SsaVarId> {
        let width = shape(&ty).0;
        let peers: Vec<SsaVarId> = self
            .scope
            .iter()
            .filter(|(_, other)| shape(other).0 == width)
            .map(|(var, _)| *var)
            .collect();
        if !peers.is_empty() && self.stream.chance(3) {
            return self.stream.pick(&peers);
        }
        self.constant(block, ty, &VALUES)
    }

    /// One operation on `value`, returning its result and type.
    fn grow(
        &mut self,
        block: usize,
        (value, ty): (SsaVarId, MockType),
    ) -> Option<(SsaVarId, MockType)> {
        let result_ty = if self.stream.chance(4) {
            flipped(ty)
        } else {
            ty
        };
        let result = match self.stream.below(12) {
            choice @ 0..=5 => {
                let right = self.operand(block, ty)?;
                self.builder.def(block, result_ty, |dest| match choice {
                    0 => SsaOp::Add {
                        dest,
                        left: value,
                        right,
                        flags: None,
                    },
                    1 => SsaOp::Sub {
                        dest,
                        left: value,
                        right,
                        flags: None,
                    },
                    2 => SsaOp::Mul {
                        dest,
                        left: value,
                        right,
                        flags: None,
                    },
                    3 => SsaOp::And {
                        dest,
                        left: value,
                        right,
                        flags: None,
                    },
                    4 => SsaOp::Or {
                        dest,
                        left: value,
                        right,
                        flags: None,
                    },
                    _ => SsaOp::Xor {
                        dest,
                        left: value,
                        right,
                        flags: None,
                    },
                })
            }
            choice @ 6..=7 => {
                let amount = self.constant(block, MockType::I32, &COUNTS)?;
                let unsigned = self.stream.chance(2);
                self.builder.def(block, result_ty, |dest| {
                    if choice == 6 {
                        SsaOp::Shl {
                            dest,
                            value,
                            amount,
                            flags: None,
                        }
                    } else {
                        SsaOp::Shr {
                            dest,
                            value,
                            amount,
                            unsigned,
                            flags: None,
                        }
                    }
                })
            }
            8 => {
                let divisor = self.operand(block, ty)?;
                let unsigned = self.stream.chance(2);
                self.builder.def(block, result_ty, |dest| SsaOp::Rem {
                    dest,
                    left: value,
                    right: divisor,
                    unsigned,
                    flags: None,
                })
            }
            9 => {
                let negate = self.stream.chance(2);
                self.builder.def(block, result_ty, |dest| {
                    if negate {
                        SsaOp::Neg {
                            dest,
                            operand: value,
                            flags: None,
                        }
                    } else {
                        SsaOp::Not {
                            dest,
                            operand: value,
                            flags: None,
                        }
                    }
                })
            }
            10 => self
                .builder
                .def(block, flipped(ty), |dest| SsaOp::Copy { dest, src: value }),
            _ => {
                let target = self.stream.pick(&INTEGERS)?;
                let unsigned = self.stream.chance(2);
                let result = self.builder.def(block, target, |dest| SsaOp::IntConv {
                    dest,
                    operand: value,
                    target,
                    overflow_check: false,
                    unsigned,
                });
                self.scope.push((result, target));
                return Some((result, target));
            }
        };
        let produced = match self.builder.ssa.variable(result) {
            Some(variable) => *variable.var_type(),
            None => result_ty,
        };
        self.scope.push((result, produced));
        Some((result, produced))
    }

    /// A comparison of `value` against an operand of its width.
    fn compare(&mut self, block: usize, (value, ty): (SsaVarId, MockType)) -> Option<SsaVarId> {
        let right = self.operand(block, ty)?;
        let unsigned = self.stream.chance(2);
        let kind = self.stream.below(3);
        Some(self.builder.def(block, MockType::I32, |dest| match kind {
            0 => SsaOp::Ceq {
                dest,
                left: value,
                right,
                signaling: false,
            },
            1 => SsaOp::Clt {
                dest,
                left: value,
                right,
                unsigned,
                signaling: false,
            },
            _ => SsaOp::Cgt {
                dest,
                left: value,
                right,
                unsigned,
                signaling: false,
            },
        }))
    }

    /// A compare-and-branch of `value` against an operand of its width.
    fn branch_cmp(
        &mut self,
        block: usize,
        (value, ty): (SsaVarId, MockType),
        true_target: usize,
        false_target: usize,
    ) -> Option<()> {
        let right = self.operand(block, ty)?;
        let cmp = self.stream.pick(&[
            CmpKind::Eq,
            CmpKind::Ne,
            CmpKind::Lt,
            CmpKind::Le,
            CmpKind::Gt,
            CmpKind::Ge,
        ])?;
        let unsigned = self.stream.chance(2);
        self.builder.end(
            block,
            SsaOp::BranchCmp {
                left: value,
                right,
                cmp,
                unsigned,
                true_target,
                false_target,
            },
        );
        Some(())
    }

    /// A chain of one to three operations on `start`, each result compared.
    fn chain(&mut self, block: usize, start: (SsaVarId, MockType)) -> Option<(SsaVarId, MockType)> {
        let mut current = start;
        for _ in 0..self.stream.below(3).wrapping_add(1) {
            current = self.grow(block, current)?;
            self.compare(block, current)?;
        }
        Some(current)
    }
}

/// A generated function and the inputs it is executed on.
struct Case {
    ssa: SsaFunction<MockTarget>,
    inputs: Vec<Vec<(SsaVarId, i128)>>,
}

/// Generates the `index`-th function of one of three shapes over one or two
/// byte inputs: straight-line arithmetic, a diamond whose arms merge in a phi,
/// and a loop whose counter is the arithmetic.
fn generate(seed: u64) -> Option<Case> {
    let mut generator = Generator {
        stream: Stream(seed),
        builder: Builder::new(4),
        scope: Vec::new(),
    };
    let x_ty = generator.stream.pick(&BYTES)?;
    let y_ty = generator.stream.pick(&BYTES)?;
    let x = generator.builder.argument(0, x_ty);
    // The second input is sometimes a local nothing in the body defines.
    let y = if generator.stream.chance(2) {
        generator.builder.entry_local(y_ty)
    } else {
        generator.builder.argument(1, y_ty)
    };
    generator.scope.push((x, x_ty));
    generator.scope.push((y, y_ty));

    match generator.stream.below(3) {
        0 => {
            let last = generator.chain(0, (x, x_ty))?;
            let result = generator.compare(0, last)?;
            generator.builder.end(0, SsaOp::returns(Some(result)));
        }
        1 => {
            let first = generator.chain(0, (x, x_ty))?;
            if generator.stream.chance(2) {
                generator.branch_cmp(0, first, 1, 2)?;
            } else if generator.stream.chance(2) {
                let condition = generator.compare(0, first)?;
                generator.builder.end(
                    0,
                    SsaOp::Branch {
                        condition,
                        true_target: 1,
                        false_target: 2,
                    },
                );
            } else {
                generator.builder.end(
                    0,
                    SsaOp::Branch {
                        condition: y,
                        true_target: 1,
                        false_target: 2,
                    },
                );
            }
            // Each arm sees only what the entry block defined.
            let dominating = generator.scope.clone();
            let (left, left_ty) = generator.chain(1, first)?;
            generator.builder.end(1, SsaOp::Jump { target: 3 });
            generator.scope.clone_from(&dominating);
            let right = generator.operand(2, left_ty)?;
            generator.builder.end(2, SsaOp::Jump { target: 3 });
            generator.scope = dominating;
            let merged = generator.builder.phi(3, left_ty);
            generator
                .builder
                .close_phi(merged, &[(left, 1), (right, 2)]);
            generator.scope.push((merged, left_ty));
            let last = generator.chain(3, (merged, left_ty))?;
            let result = generator.compare(3, last)?;
            generator.builder.end(3, SsaOp::returns(Some(result)));
        }
        _ => {
            let start = generator.chain(0, (x, x_ty))?;
            generator.builder.end(0, SsaOp::Jump { target: 1 });
            let counter = generator.builder.phi(1, start.1);
            generator.scope.push((counter, start.1));
            generator.branch_cmp(1, (counter, start.1), 2, 3)?;
            // The exit sees what the header's dominators defined, not the body.
            let dominating = generator.scope.clone();
            let step = generator.operand(2, start.1)?;
            let add = generator.stream.chance(2);
            let next = generator.builder.def(2, start.1, |dest| {
                if add {
                    SsaOp::Add {
                        dest,
                        left: counter,
                        right: step,
                        flags: None,
                    }
                } else {
                    SsaOp::Xor {
                        dest,
                        left: counter,
                        right: step,
                        flags: None,
                    }
                }
            });
            generator.compare(2, (next, start.1))?;
            generator.builder.end(2, SsaOp::Jump { target: 1 });
            generator
                .builder
                .close_phi(counter, &[(start.0, 0), (next, 2)]);
            generator.scope = dominating;
            let result = generator.compare(3, (counter, start.1))?;
            generator.builder.end(3, SsaOp::returns(Some(result)));
        }
    }

    let ssa = generator.builder.finish();
    let mut inputs = Vec::new();
    for x_value in 0..=255i128 {
        for y_value in [0i128, 0x80] {
            inputs.push(vec![(x, x_value), (y, y_value)]);
        }
    }
    Some(Case { ssa, inputs })
}

/// How many functions the property generates.
const GENERATED: u64 = 300;

/// **Every fold the range pass makes on an 8-bit function is true of every
/// input.**
///
/// The functions are generated from one or two byte inputs - signed and
/// unsigned, an argument or a local nothing defines - through arithmetic,
/// bitwise operations, shifts (including counts at and past the width),
/// remainders, re-typing copies and conversions to every width, as straight
/// code, a diamond merged by a phi, and a loop. Each is executed on all 256
/// values of its first input, and every comparison or conditional branch the
/// pass replaced by a constant must have come out that way on every run.
#[test]
fn every_fold_on_a_byte_function_holds_for_every_input() {
    let mut folds = 0usize;
    let mut functions = 0usize;
    for seed in 0..GENERATED {
        let Some(case) = generate(seed.wrapping_mul(0x9E37_79B9).wrapping_add(17)) else {
            continue;
        };
        assert_eq!(case.ssa.validate(), Ok(()), "seed {seed}:\n{}", case.ssa);
        let checked = folds_agree_with_execution(&case.ssa, &case.inputs);
        assert!(checked.is_ok(), "seed {seed}: {checked:?}");
        folds = folds.wrapping_add(checked.unwrap_or(0));
        functions = functions.wrapping_add(1);
    }
    assert!(
        functions > 250,
        "the generator built too few functions: {functions}"
    );
    // Not vacuous: the pass does decide comparisons in these functions.
    assert!(folds > 100, "only {folds} folds were checked");
}

/// The same guard, fused into the terminator, proves the same bound.
///
/// A native target never emits the unfused spelling: `cmp` sets flags and the
/// branch tests them, or the comparison is part of the branch. Reading only
/// `Branch` meant this refinement learned nothing at all about a lifted binary,
/// which is most of what the crate's other consumer analyses.
#[test]
fn a_fused_compare_and_branch_bounds_the_value_too() {
    let mut ssa: SsaFunction<MockTarget> = SsaFunction::new(1, 8);
    let idx = ssa.create_variable(
        VariableOrigin::Argument(0),
        0,
        DefSite::entry(),
        MockType::I32,
    );
    let limit = var(&mut ssa, 1, 0, 0);

    let mut b0 = SsaBlock::new(0);
    b0.add_instruction(instr(SsaOp::Const {
        dest: limit,
        value: ConstValue::I32(4),
    }));
    b0.add_instruction(instr(SsaOp::BranchCmp {
        left: idx,
        right: limit,
        cmp: CmpKind::Gt,
        unsigned: false,
        true_target: 1,
        false_target: 2,
    }));
    ssa.add_block(b0);

    for block_id in [1usize, 2] {
        let mut arm = SsaBlock::new(block_id);
        arm.add_instruction(instr(SsaOp::returns(Some(idx))));
        ssa.add_block(arm);
    }
    ssa.recompute_uses();

    let cfg = SsaCfg::from_ssa(&ssa);
    let dominators = compute_dominators(&cfg, cfg.entry());
    let Ok(ranges) = analyze(&ssa, &budget(64), &BTreeMap::new()) else {
        return;
    };

    assert!(
        ranges.get(idx).cloned().unwrap_or_default().max().is_none(),
        "an argument is unbounded overall"
    );
    assert_eq!(
        ranges.range_at(&ssa, &dominators, idx, 2).max(),
        Some(4),
        "the arm `idx > 4` does not admit bounds idx at 4"
    );
    assert_eq!(
        ranges.range_at(&ssa, &dominators, idx, 1).min(),
        Some(5),
        "and the arm it does admit puts idx above the limit"
    );
}
