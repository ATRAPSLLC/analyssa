//! Soundness of the value-range pass.
//!
//! The engine is SCCP-shaped: it narrows from `Top` while discovering which CFG
//! edges are executable, and its conclusions are only sound *at* the fixpoint.
//! Stopping early leaves an incomplete executable-edge set and ranges that are
//! too narrow - which is the unsound direction, because a too-narrow range
//! proves comparisons that are not actually provable.
//!
//! The other half is machine arithmetic: every fold the pass makes is checked
//! against a reference interpreter that computes at each value's width and
//! signedness, on hand-built shapes and on generated byte-sized functions
//! executed for every input byte.

use std::collections::BTreeMap;

use analyssa::{
    analysis::{
        budget::{Budget, WorkBudget},
        cfg::SsaCfg,
        context::AnalysisContext,
        dataflow::{DataFlowAnalysis, DataFlowSolver, Direction},
        range::ValueRange,
    },
    events::NullListener,
    graph::{RootedGraph, algorithms::compute_dominators},
    ir::{
        CmpKind,
        block::SsaBlock,
        function::SsaFunction,
        instruction::SsaInstruction,
        ops::SsaOp,
        phi::{PhiNode, PhiOperand},
        value::ConstValue,
        variable::{DefSite, SsaVarId, VariableOrigin},
    },
    passes::{
        ValueRangePropagationPass,
        ranges::{GuardedRanges, analyze},
    },
    scheduling::{FunctionPass, PassEnv},
    testing::{MACHINE, MockTarget, MockType},
};
use rustc_hash::FxHashMap;

/// The default budget with the range fixpoint given `limit` rounds.
fn budget(limit: usize) -> WorkBudget {
    WorkBudget::DEFAULT.with_limit(Budget::RangeRounds, limit)
}

fn instr(op: SsaOp<MockTarget>) -> SsaInstruction<MockTarget> {
    SsaInstruction::synthetic(op)
}

fn var(ssa: &mut SsaFunction<MockTarget>, idx: u16, block: usize, instruction: usize) -> SsaVarId {
    ssa.create_variable(
        VariableOrigin::Local(idx),
        0,
        DefSite::instruction(block, instruction),
        MockType::I32,
    )
}

/// Builds the counted loop
///
/// ```text
/// b0: i0 = 0;                jump b1
/// b1: i = phi(i0:b0, i2:b2); c = i < 10; branch c ? b2 : b3
/// b2: i2 = i + 1;            jump b1
/// b3: return i
/// ```
///
/// The loop exit in `b1` is reachable - `i` runs 0..=10 - so nothing here may
/// be folded away.
fn counted_loop() -> SsaFunction<MockTarget> {
    let mut ssa = SsaFunction::new(0, 12);
    let start = var(&mut ssa, 0, 0, 0);
    let limit = var(&mut ssa, 1, 1, 0);
    let counter = var(&mut ssa, 2, 1, 0);
    let condition = var(&mut ssa, 3, 1, 1);
    let step = var(&mut ssa, 4, 2, 0);
    let next = var(&mut ssa, 5, 2, 1);

    let mut b0 = SsaBlock::new(0);
    b0.add_instruction(instr(SsaOp::Const {
        dest: start,
        value: ConstValue::I32(0),
    }));
    b0.add_instruction(instr(SsaOp::Jump { target: 1 }));
    ssa.add_block(b0);

    let mut b1 = SsaBlock::new(1);
    let mut phi = PhiNode::new(counter, VariableOrigin::Local(2));
    phi.add_operand(PhiOperand::new(start, 0));
    phi.add_operand(PhiOperand::new(next, 2));
    b1.add_phi(phi);
    b1.add_instruction(instr(SsaOp::Const {
        dest: limit,
        value: ConstValue::I32(10),
    }));
    b1.add_instruction(instr(SsaOp::Clt {
        dest: condition,
        left: counter,
        right: limit,
        unsigned: false,
        signaling: false,
    }));
    b1.add_instruction(instr(SsaOp::Branch {
        condition,
        true_target: 2,
        false_target: 3,
    }));
    ssa.add_block(b1);

    let mut b2 = SsaBlock::new(2);
    b2.add_instruction(instr(SsaOp::Const {
        dest: step,
        value: ConstValue::I32(1),
    }));
    b2.add_instruction(instr(SsaOp::Add {
        dest: next,
        left: counter,
        right: step,
        flags: None,
    }));
    b2.add_instruction(instr(SsaOp::Jump { target: 1 }));
    ssa.add_block(b2);

    let mut b3 = SsaBlock::new(3);
    b3.add_instruction(instr(SsaOp::returns(Some(counter))));
    ssa.add_block(b3);

    ssa.recompute_uses();
    ssa
}

/// Returns `true` when block 1 still ends in a conditional branch.
fn exit_branch_survives(ssa: &SsaFunction<MockTarget>) -> bool {
    ssa.block(1)
        .and_then(|block| block.control_terminator())
        .is_some_and(|op| matches!(op, SsaOp::Branch { .. }))
}

/// Returns `true` while block 1 still contains the `i < limit` comparison -
/// i.e. it has not been folded to a constant.
fn comparison_survives(ssa: &SsaFunction<MockTarget>) -> bool {
    ssa.block(1).is_some_and(|block| {
        block
            .instructions()
            .iter()
            .any(|instruction| matches!(instruction.op(), SsaOp::Clt { .. }))
    })
}

/// The loop's guard is genuinely not provable - `i` reaches the limit - so the
/// comparison must survive at every iteration budget.
///
/// The analysis is optimistic, so a truncated run holds a range for `i` that
/// is too narrow and would fold `i < 10` to a constant `true`. A comparison
/// result is modelled as `[0,1]` rather than a truth value, so the branch can
/// survive that first run - but the folded constant would let the *next*
/// pipeline iteration delete the loop exit, turning the loop infinite. Small
/// budgets such as `max_iterations = 8` are the ones a lifter uses.
#[test]
fn truncated_fixpoint_does_not_prove_a_loop_guard() {
    for max_iterations in [1usize, 2, 3, 4, 6, 8, 12, 16, 32, 64, 256] {
        let mut ssa = counted_loop();
        assert!(
            ValueRangePropagationPass
                .run(
                    &mut ssa,
                    &PassEnv::new(&0u32, &NullListener, AnalysisContext::new(MACHINE))
                        .with_budget(budget(max_iterations))
                )
                .is_ok()
        );
        assert!(
            comparison_survives(&ssa),
            "loop guard folded to a constant at max_iterations={max_iterations}"
        );
        assert_eq!(ssa.validate(), Ok(()));
    }
}

/// Running the pass twice - as the normalization fixpoint does - must not
/// delete the loop exit. This is the end of the miscompilation path above.
#[test]
fn repeated_runs_do_not_delete_the_loop_exit() {
    for max_iterations in [1usize, 4, 8, 64] {
        let mut ssa = counted_loop();
        for _ in 0..4 {
            assert!(
                ValueRangePropagationPass
                    .run(
                        &mut ssa,
                        &PassEnv::new(&0u32, &NullListener, AnalysisContext::new(MACHINE))
                            .with_budget(budget(max_iterations))
                    )
                    .is_ok()
            );
        }
        assert!(
            exit_branch_survives(&ssa),
            "loop exit deleted at max_iterations={max_iterations}"
        );
        assert_eq!(ssa.validate(), Ok(()));
    }
}

/// A counted loop's exit must survive range propagation no matter how few
/// iterations the engine is given: a truncated fixpoint that still believes
/// `i` is small would fold the exit away and turn the loop infinite.
#[test]
fn truncated_fixpoint_does_not_fold_a_live_loop_exit() {
    for max_iterations in [1usize, 2, 4, 8, 16, 64] {
        let mut ssa = counted_loop();
        assert!(
            ValueRangePropagationPass
                .run(
                    &mut ssa,
                    &PassEnv::new(&0u32, &NullListener, AnalysisContext::new(MACHINE))
                        .with_budget(budget(max_iterations))
                )
                .is_ok()
        );
        assert!(
            exit_branch_survives(&ssa),
            "loop exit folded away at max_iterations={max_iterations}"
        );
        assert_eq!(ssa.validate(), Ok(()));
    }
}

/// Builds `x = a + b; c = x < 0; branch c ? b1 : b2` with all values typed
/// `i32`.
fn add_then_compare_against_zero(a: i32, b: i32) -> SsaFunction<MockTarget> {
    let mut ssa = SsaFunction::new(0, 10);
    let left = var(&mut ssa, 0, 0, 0);
    let right = var(&mut ssa, 1, 0, 1);
    let sum = var(&mut ssa, 2, 0, 2);
    let zero = var(&mut ssa, 3, 0, 3);
    let condition = var(&mut ssa, 4, 0, 4);

    let mut b0 = SsaBlock::new(0);
    b0.add_instruction(instr(SsaOp::Const {
        dest: left,
        value: ConstValue::I32(a),
    }));
    b0.add_instruction(instr(SsaOp::Const {
        dest: right,
        value: ConstValue::I32(b),
    }));
    b0.add_instruction(instr(SsaOp::Add {
        dest: sum,
        left,
        right,
        flags: None,
    }));
    b0.add_instruction(instr(SsaOp::Const {
        dest: zero,
        value: ConstValue::I32(0),
    }));
    b0.add_instruction(instr(SsaOp::Clt {
        dest: condition,
        left: sum,
        right: zero,
        unsigned: false,
        signaling: false,
    }));
    b0.add_instruction(instr(SsaOp::Branch {
        condition,
        true_target: 1,
        false_target: 2,
    }));
    ssa.add_block(b0);

    let mut b1 = SsaBlock::new(1);
    b1.add_instruction(instr(SsaOp::returns(Some(sum))));
    ssa.add_block(b1);

    let mut b2 = SsaBlock::new(2);
    b2.add_instruction(instr(SsaOp::returns(Some(sum))));
    ssa.add_block(b2);

    ssa.recompute_uses();
    ssa
}

/// Arithmetic that overflows its destination width is read at that width.
///
/// Interval arithmetic runs on integers, but a 32-bit `add` wraps:
/// `0x7fff_ffff + 1` is `-0x8000_0000`, not `0x8000_0000`. Reading the
/// integer result would conclude the sum is positive and fold `sum < 0` to
/// `false` - the opposite of the truth. Whatever the pass decides has to be
/// what the machine computes.
#[test]
fn overflowing_arithmetic_does_not_prove_a_sign() {
    let ssa = add_then_compare_against_zero(i32::MAX, 1);
    let checked = folds_agree_with_execution(&ssa, &[Vec::new()]);
    assert!(checked.is_ok(), "{checked:?}");
}

/// The control: an add that stays in range still proves its sign, so the test
/// above is not passing merely because the analysis gave up everywhere.
#[test]
fn in_range_arithmetic_still_proves_a_sign() {
    let ssa = add_then_compare_against_zero(2, 3);
    let checked = folds_agree_with_execution(&ssa, &[Vec::new()]);
    assert!(
        checked.as_ref().is_ok_and(|folds| *folds > 0),
        "an in-range add still folds the comparison: {checked:?}"
    );
}

/// Builds a guarded dispatch:
///
/// ```text
/// b0: idx = <opaque>; limit = 4; c = idx > limit; branch c ? b1 : b2
/// b1: return idx                      (out of range)
/// b2: return idx                      (guarded: idx <= 4)
/// ```
///
/// `idx` is an argument, so the whole-function range proves nothing about it.
/// Only the path through `b2` is bounded - the fact a switch dispatch needs.
fn guarded_dispatch() -> (SsaFunction<MockTarget>, SsaVarId) {
    let mut ssa = SsaFunction::new(1, 8);
    let idx = ssa.create_variable(
        VariableOrigin::Argument(0),
        0,
        DefSite::entry(),
        MockType::I32,
    );
    let limit = var(&mut ssa, 1, 0, 0);
    let condition = var(&mut ssa, 2, 0, 1);

    let mut b0 = SsaBlock::new(0);
    b0.add_instruction(instr(SsaOp::Const {
        dest: limit,
        value: ConstValue::I32(4),
    }));
    b0.add_instruction(instr(SsaOp::Cgt {
        dest: condition,
        left: idx,
        right: limit,
        unsigned: false,
        signaling: false,
    }));
    b0.add_instruction(instr(SsaOp::Branch {
        condition,
        true_target: 1,
        false_target: 2,
    }));
    ssa.add_block(b0);

    let mut b1 = SsaBlock::new(1);
    b1.add_instruction(instr(SsaOp::returns(Some(idx))));
    ssa.add_block(b1);

    let mut b2 = SsaBlock::new(2);
    b2.add_instruction(instr(SsaOp::returns(Some(idx))));
    ssa.add_block(b2);

    ssa.recompute_uses();
    (ssa, idx)
}

/// A guard on a byte bounds the byte's zero-extension too, computed before
/// the guard: a switch compares `126 <u c` and indexes its table by `c`
/// widened to a word. On the arm the guard admits the word is at most `126`,
/// and on the other at least `127`.
#[test]
fn a_guard_on_a_value_bounds_its_conversions() {
    let mut ssa = SsaFunction::new(1, 8);
    let byte = ssa.create_variable(
        VariableOrigin::Argument(0),
        0,
        DefSite::entry(),
        MockType::U8,
    );
    let wide = ssa.create_variable(
        VariableOrigin::Local(0),
        0,
        DefSite::instruction(0, 0),
        MockType::U64,
    );
    let limit = ssa.create_variable(
        VariableOrigin::Local(1),
        0,
        DefSite::instruction(0, 1),
        MockType::U8,
    );
    let mut b0 = SsaBlock::new(0);
    b0.add_instruction(instr(SsaOp::IntConv {
        dest: wide,
        operand: byte,
        target: MockType::U64,
        overflow_check: false,
        unsigned: true,
    }));
    b0.add_instruction(instr(SsaOp::Const {
        dest: limit,
        value: ConstValue::U8(126),
    }));
    b0.add_instruction(instr(SsaOp::BranchCmp {
        left: limit,
        right: byte,
        cmp: CmpKind::Lt,
        unsigned: true,
        true_target: 1,
        false_target: 2,
    }));
    ssa.add_block(b0);
    for index in [1, 2] {
        let mut block = SsaBlock::new(index);
        block.add_instruction(instr(SsaOp::returns(Some(wide))));
        ssa.add_block(block);
    }
    ssa.recompute_uses();
    let cfg = SsaCfg::from_ssa(&ssa);
    let dominators = compute_dominators(&cfg, cfg.entry());
    let converged = analyze(&ssa, &budget(64), &BTreeMap::new());
    assert!(converged.is_ok(), "the analysis converges on a diamond");
    let Ok(ranges) = converged else { return };
    let admitted = ranges.range_at(&ssa, &dominators, wide, 2);
    assert_eq!((admitted.min(), admitted.max()), (Some(0), Some(126)));
    let rejected = ranges.range_at(&ssa, &dominators, wide, 1);
    assert_eq!((rejected.min(), rejected.max()), (Some(127), Some(255)));
}

/// A dominating guard bounds the value on the arm it admits, and only there.
///
/// The whole-function range for an argument is `Top`; the bound exists only on
/// the guarded path. Without this refinement a switch index carries no bound at
/// all, which is why jump-table recovery cannot be driven from the
/// whole-function range alone.
#[test]
fn a_dominating_guard_bounds_the_value_on_its_arm() {
    let (ssa, idx) = guarded_dispatch();
    let cfg = SsaCfg::from_ssa(&ssa);
    let dominators = compute_dominators(&cfg, cfg.entry());
    let converged = analyze(&ssa, &budget(64), &BTreeMap::new());
    assert!(
        converged.is_ok(),
        "the analysis converges on a diamond this small"
    );
    let Ok(ranges) = converged else { return };

    // Whole-function: an argument is unconstrained.
    let global = ranges.get(idx).cloned().unwrap_or_default();
    assert!(global.max().is_none(), "argument is unbounded overall");

    // On the guarded arm `idx > 4` was false, so `idx <= 4`.
    let guarded = ranges.range_at(&ssa, &dominators, idx, 2);
    assert_eq!(
        guarded.max(),
        Some(4),
        "the false arm of `idx > 4` bounds idx at 4"
    );

    // On the other arm `idx > 4` held, so `idx >= 5`.
    let out_of_range = ranges.range_at(&ssa, &dominators, idx, 1);
    assert_eq!(
        out_of_range.min(),
        Some(5),
        "the true arm of `idx > 4` puts idx above the limit"
    );

    // The entry block is before the guard: nothing is proved there.
    let at_entry = ranges.range_at(&ssa, &dominators, idx, 0);
    assert!(
        at_entry.max().is_none(),
        "the guard proves nothing above itself"
    );
}

/// A range analysis driven by the *generic* dataflow solver terminates, which
/// it cannot without the widening hook.
///
/// The solver has no iteration cap - it drains its worklist and relies on the
/// lattice having finite height. `ValueRange` does not: a counted loop grows
/// its interval by one per trip, so an exact solver runs once per trip and a
/// genuinely unbounded loop never finishes. `widen` is what bounds it.
#[test]
fn the_solver_widening_hook_terminates_an_interval_analysis() {
    /// Counts up by one per block visit - an intentionally unbounded ascent.
    struct CountingAnalysis {
        widen_after: usize,
    }

    impl DataFlowAnalysis<MockTarget> for CountingAnalysis {
        type Lattice = ValueRange;
        const DIRECTION: Direction = Direction::Forward;

        fn boundary(&self, _ssa: &SsaFunction<MockTarget>) -> ValueRange {
            ValueRange::constant(0)
        }

        fn initial(&self, _ssa: &SsaFunction<MockTarget>) -> ValueRange {
            ValueRange::bottom()
        }

        fn transfer(
            &self,
            _block_id: usize,
            _block: &SsaBlock<MockTarget>,
            input: &ValueRange,
            _ssa: &SsaFunction<MockTarget>,
        ) -> ValueRange {
            // Every pass shifts the interval up by one; nothing converges.
            input.add(&ValueRange::constant(1))
        }

        fn widen(
            &self,
            _block_id: usize,
            previous: &ValueRange,
            next: ValueRange,
            visit: usize,
        ) -> ValueRange {
            if visit > self.widen_after {
                previous.widen(&next)
            } else {
                next
            }
        }
    }

    let ssa = counted_loop();
    let cfg = SsaCfg::from_ssa(&ssa);
    let analysis = CountingAnalysis { widen_after: 3 };
    let solver = DataFlowSolver::new(analysis);

    // Without widening this call does not return: the transfer function climbs
    // by one every visit and the loop's back edge keeps re-queueing the header.
    // Reaching the assertions at all is half the result.
    let results = solver.solve(&ssa, &cfg);
    assert_eq!(
        results.in_states.len(),
        ssa.block_count(),
        "the solver reached a fixpoint and produced one state per block"
    );
    // ...and the other half: widening is what stopped it, so some state must
    // have been pushed to an infinite bound rather than converging on its own.
    assert!(
        results
            .out_states
            .iter()
            .any(|state| state.max().is_none() || state.is_top()),
        "termination came from widening, not from the ascent settling"
    );
}

/// Builds a loop whose latch is a `BranchCmp` - the compare-and-branch form
/// that states its comparison inline and names no condition variable.
///
/// ```text
/// b0: i0 = 0; bound = <bound>;   jump b1
/// b1: i = phi(i0:b0, i2:b2);     branch_cmp i < bound ? b2 : b3
/// b2: i2 = i + 1;                jump b1
/// b3: return i
/// ```
///
/// With `bound = 0` the body is unreachable: `i` starts at `0` and only grows,
/// so `i < 0` is false on every path. With `bound = 10` the loop is live and
/// the latch must survive.
fn branch_cmp_loop(bound: i32) -> SsaFunction<MockTarget> {
    let mut ssa = SsaFunction::new(0, 12);
    let start = var(&mut ssa, 0, 0, 0);
    let limit = var(&mut ssa, 1, 0, 1);
    let counter = var(&mut ssa, 2, 1, 0);
    let step = var(&mut ssa, 3, 2, 0);
    let next = var(&mut ssa, 4, 2, 1);

    let mut b0 = SsaBlock::new(0);
    b0.add_instruction(instr(SsaOp::Const {
        dest: start,
        value: ConstValue::I32(0),
    }));
    b0.add_instruction(instr(SsaOp::Const {
        dest: limit,
        value: ConstValue::I32(bound),
    }));
    b0.add_instruction(instr(SsaOp::Jump { target: 1 }));
    ssa.add_block(b0);

    let mut b1 = SsaBlock::new(1);
    let mut phi = PhiNode::new(counter, VariableOrigin::Local(2));
    phi.add_operand(PhiOperand::new(start, 0));
    phi.add_operand(PhiOperand::new(next, 2));
    b1.add_phi(phi);
    b1.add_instruction(instr(SsaOp::BranchCmp {
        left: counter,
        right: limit,
        cmp: CmpKind::Lt,
        unsigned: false,
        true_target: 2,
        false_target: 3,
    }));
    ssa.add_block(b1);

    let mut b2 = SsaBlock::new(2);
    b2.add_instruction(instr(SsaOp::Const {
        dest: step,
        value: ConstValue::I32(1),
    }));
    b2.add_instruction(instr(SsaOp::Add {
        dest: next,
        left: counter,
        right: step,
        flags: None,
    }));
    b2.add_instruction(instr(SsaOp::Jump { target: 1 }));
    ssa.add_block(b2);

    let mut b3 = SsaBlock::new(3);
    b3.add_instruction(instr(SsaOp::returns(Some(counter))));
    ssa.add_block(b3);

    ssa.recompute_uses();
    ssa
}

/// Returns `true` when block 1 still ends in a compare-and-branch.
fn branch_cmp_survives(ssa: &SsaFunction<MockTarget>) -> bool {
    ssa.block(1)
        .and_then(|block| block.control_terminator())
        .is_some_and(|op| matches!(op, SsaOp::BranchCmp { .. }))
}

/// A live `BranchCmp` latch is never folded.
///
/// The counterpart of the zero-trip fold, and the direction this file exists to
/// defend: `i` really does reach `10`, so `i < 10` is not a provable truth and
/// deleting either edge would turn the loop infinite or drop its body. The
/// analysis is optimistic, so a truncated fixpoint holds ranges that are too
/// narrow - which is exactly when a terminator fold is most tempting and most
/// wrong.
#[test]
fn a_live_compare_and_branch_latch_is_never_folded() {
    for max_iterations in [1usize, 2, 3, 4, 6, 8, 12, 16, 32, 64, 256] {
        let mut ssa = branch_cmp_loop(10);
        for _ in 0..4 {
            assert!(
                ValueRangePropagationPass
                    .run(
                        &mut ssa,
                        &PassEnv::new(&0u32, &NullListener, AnalysisContext::new(MACHINE))
                            .with_budget(budget(max_iterations))
                    )
                    .is_ok()
            );
        }
        assert!(
            branch_cmp_survives(&ssa),
            "live latch folded at max_iterations={max_iterations}"
        );
        assert_eq!(ssa.validate(), Ok(()));
    }
}

/// With `bound = 0` the latch is decided: `i` is `0` on entry and the back
/// edge is never taken, so `i < 0` is false and the body is unreachable.
#[test]
fn a_zero_trip_compare_and_branch_latch_folds_to_its_exit() {
    let mut ssa = branch_cmp_loop(0);
    assert!(
        ValueRangePropagationPass
            .run(
                &mut ssa,
                &PassEnv::new(&0u32, &NullListener, AnalysisContext::new(MACHINE))
                    .with_budget(budget(64))
            )
            .is_ok()
    );
    assert!(
        matches!(
            ssa.block(1).and_then(SsaBlock::control_terminator),
            Some(SsaOp::Jump { target: 3 })
        ),
        "`i < 0` with `i = 0` is false on every path, got {:?}",
        ssa.block(1).and_then(SsaBlock::control_terminator)
    );
    assert_eq!(ssa.validate(), Ok(()));
}

/// A phi whose result is reserved: its block, its result, and the operands
/// gathered for it so far.
type PendingPhi = (usize, SsaVarId, Vec<(SsaVarId, usize)>);

/// Builds a function block by block, giving every definition its real site.
struct Builder {
    ssa: SsaFunction<MockTarget>,
    blocks: Vec<SsaBlock<MockTarget>>,
    phis: Vec<PendingPhi>,
    locals: u16,
}

impl Builder {
    fn new(block_count: usize) -> Self {
        Self {
            ssa: SsaFunction::new(2, 64),
            blocks: (0..block_count).map(SsaBlock::new).collect(),
            phis: Vec::new(),
            locals: 0,
        }
    }

    fn next_origin(&mut self) -> VariableOrigin {
        let origin = VariableOrigin::Local(self.locals);
        self.locals = self.locals.wrapping_add(1);
        origin
    }

    /// A caller-supplied argument.
    fn argument(&mut self, index: u16, ty: MockType) -> SsaVarId {
        self.ssa
            .create_variable(VariableOrigin::Argument(index), 0, DefSite::entry(), ty)
    }

    /// A local defined on entry by nothing in the body.
    fn entry_local(&mut self, ty: MockType) -> SsaVarId {
        let origin = self.next_origin();
        self.ssa.create_variable(origin, 0, DefSite::entry(), ty)
    }

    fn def(
        &mut self,
        block: usize,
        ty: MockType,
        op: impl FnOnce(SsaVarId) -> SsaOp<MockTarget>,
    ) -> SsaVarId {
        let origin = self.next_origin();
        let index = self.blocks.get(block).map_or(0, |b| b.instructions().len());
        let var = self
            .ssa
            .create_variable(origin, 0, DefSite::instruction(block, index), ty);
        if let Some(target) = self.blocks.get_mut(block) {
            target.add_instruction(instr(op(var)));
        }
        var
    }

    fn constant(&mut self, block: usize, ty: MockType, value: ConstValue<MockTarget>) -> SsaVarId {
        self.def(block, ty, |dest| SsaOp::Const { dest, value })
    }

    /// Reserves a phi result; its operands are supplied by [`Self::close_phi`].
    fn phi(&mut self, block: usize, ty: MockType) -> SsaVarId {
        let origin = self.next_origin();
        let var = self.ssa.create_variable(origin, 0, DefSite::phi(block), ty);
        self.phis.push((block, var, Vec::new()));
        var
    }

    fn close_phi(&mut self, var: SsaVarId, operands: &[(SsaVarId, usize)]) {
        for (_, result, collected) in &mut self.phis {
            if *result == var {
                collected.extend_from_slice(operands);
            }
        }
    }

    fn end(&mut self, block: usize, op: SsaOp<MockTarget>) {
        if let Some(target) = self.blocks.get_mut(block) {
            target.add_instruction(instr(op));
        }
    }

    fn finish(self) -> SsaFunction<MockTarget> {
        let Self {
            mut ssa,
            mut blocks,
            phis,
            ..
        } = self;
        for (block, result, operands) in phis {
            let origin = ssa
                .variable(result)
                .map_or(VariableOrigin::Local(0), |v| v.origin());
            let mut phi = PhiNode::new(result, origin);
            for (value, predecessor) in operands {
                phi.add_operand(PhiOperand::new(value, predecessor));
            }
            if let Some(target) = blocks.get_mut(block) {
                target.add_phi(phi);
            }
        }
        for block in blocks {
            ssa.add_block(block);
        }
        ssa.recompute_uses();
        ssa
    }
}

/// The width and signedness a variable of `ty` holds its value in. An untyped
/// value is taken to be a 64-bit native integer.
fn shape(ty: &MockType) -> (u32, bool) {
    match ty {
        MockType::I8 => (8, true),
        MockType::U8 => (8, false),
        MockType::I16 => (16, true),
        MockType::U16 => (16, false),
        MockType::I32 => (32, true),
        MockType::U32 => (32, false),
        MockType::U64 => (64, false),
        MockType::Mask4 => (4, false),
        _ => (64, true),
    }
}

/// The `width`-bit machine value `value` denotes, read signed or unsigned.
fn wrap(value: i128, (width, signed): (u32, bool)) -> i128 {
    let modulus = 1i128.wrapping_shl(width);
    let low = value.rem_euclid(modulus);
    if signed && low >= modulus.wrapping_shr(1) {
        low.wrapping_sub(modulus)
    } else {
        low
    }
}

/// What a shift by at least the value's width produces. The IR leaves it
/// undefined, so a fold has to hold under both readings.
#[derive(Debug, Clone, Copy)]
enum Oversized {
    /// The count is reduced modulo the width, as x86 does.
    Masked,
    /// Every bit is shifted out.
    Zero,
}

/// The decisions a pass run made: comparisons replaced by a constant and
/// conditional terminators replaced by a jump.
#[derive(Debug, Default)]
struct Verdicts {
    comparisons: FxHashMap<SsaVarId, bool>,
    branches: FxHashMap<usize, usize>,
}

impl Verdicts {
    fn of(original: &SsaFunction<MockTarget>, transformed: &SsaFunction<MockTarget>) -> Self {
        let mut verdicts = Self::default();
        let mut compared: Vec<SsaVarId> = Vec::new();
        for (_, block) in original.iter_blocks() {
            for instruction in block.instructions() {
                if let SsaOp::Ceq { dest, .. } | SsaOp::Clt { dest, .. } | SsaOp::Cgt { dest, .. } =
                    instruction.op()
                {
                    compared.push(*dest);
                }
            }
        }
        for (index, block) in transformed.iter_blocks() {
            for instruction in block.instructions() {
                if let SsaOp::Const { dest, value } = instruction.op()
                    && compared.contains(dest)
                {
                    match value {
                        ConstValue::True => verdicts.comparisons.insert(*dest, true),
                        ConstValue::False => verdicts.comparisons.insert(*dest, false),
                        _ => None,
                    };
                }
            }
            let was_conditional = original
                .block(index)
                .and_then(SsaBlock::control_terminator)
                .is_some_and(|op| {
                    matches!(
                        op,
                        SsaOp::Branch { .. } | SsaOp::BranchCmp { .. } | SsaOp::BranchFlags { .. }
                    )
                });
            if was_conditional && let Some(SsaOp::Jump { target }) = block.control_terminator() {
                verdicts.branches.insert(index, *target);
            }
        }
        verdicts
    }

    fn count(&self) -> usize {
        self.comparisons.len().wrapping_add(self.branches.len())
    }
}

/// A reference interpreter over the ops the generated functions use.
struct Machine {
    /// Each variable's shape, by index.
    shapes: Vec<(u32, bool)>,
    /// Each variable's value, by index, once written.
    values: Vec<Option<i128>>,
    oversized: Oversized,
}

impl Machine {
    fn new(ssa: &SsaFunction<MockTarget>, oversized: Oversized) -> Self {
        let shapes: Vec<(u32, bool)> = (0..ssa.variable_count())
            .map(|index| {
                ssa.variable(SsaVarId::from_index(index))
                    .map_or((64, true), |v| shape(v.var_type()))
            })
            .collect();
        Self {
            values: vec![None; shapes.len()],
            shapes,
            oversized,
        }
    }

    fn shape_of(&self, var: SsaVarId) -> (u32, bool) {
        self.shapes.get(var.index()).copied().unwrap_or((64, true))
    }

    fn get(&self, var: SsaVarId) -> Result<i128, String> {
        self.values
            .get(var.index())
            .copied()
            .flatten()
            .ok_or_else(|| format!("{var:?} read before it was written"))
    }

    fn read(&self, var: SsaVarId, signed: bool) -> Result<i128, String> {
        Ok(wrap(self.get(var)?, (self.shape_of(var).0, signed)))
    }

    fn set(&mut self, dest: SsaVarId, value: i128) {
        let shape = self.shape_of(dest);
        if let Some(slot) = self.values.get_mut(dest.index()) {
            *slot = Some(wrap(value, shape));
        }
    }

    /// The count a shift of `value` by `amount` uses, or `None` when every
    /// bit is shifted out.
    fn shift_count(&self, value: SsaVarId, amount: SsaVarId) -> Result<Option<u32>, String> {
        let width = self.shape_of(value).0;
        let count = self.read(amount, false)?;
        let width_wide = i128::from(width);
        if count < width_wide {
            return Ok(u32::try_from(count).ok());
        }
        Ok(match self.oversized {
            Oversized::Masked => u32::try_from(count.rem_euclid(width_wide)).ok(),
            Oversized::Zero => None,
        })
    }

    /// Executes one non-terminator; `Ok(false)` when it traps.
    fn step(&mut self, op: &SsaOp<MockTarget>) -> Result<bool, String> {
        match op {
            SsaOp::Const { dest, value } => {
                let bits = value
                    .as_i64()
                    .map(i128::from)
                    .or_else(|| value.as_u64().map(i128::from))
                    .ok_or_else(|| format!("constant {value:?} is not an integer"))?;
                self.set(*dest, bits);
            }
            SsaOp::Copy { dest, src } => {
                let value = self.get(*src)?;
                self.set(*dest, value);
            }
            SsaOp::Add {
                dest, left, right, ..
            } => {
                let value = self.get(*left)?.wrapping_add(self.get(*right)?);
                self.set(*dest, value);
            }
            SsaOp::Sub {
                dest, left, right, ..
            } => {
                let value = self.get(*left)?.wrapping_sub(self.get(*right)?);
                self.set(*dest, value);
            }
            SsaOp::Mul {
                dest, left, right, ..
            } => {
                let value = self.get(*left)?.wrapping_mul(self.get(*right)?);
                self.set(*dest, value);
            }
            SsaOp::And {
                dest, left, right, ..
            } => {
                let value = self.get(*left)? & self.get(*right)?;
                self.set(*dest, value);
            }
            SsaOp::Or {
                dest, left, right, ..
            } => {
                let value = self.get(*left)? | self.get(*right)?;
                self.set(*dest, value);
            }
            SsaOp::Xor {
                dest, left, right, ..
            } => {
                let value = self.get(*left)? ^ self.get(*right)?;
                self.set(*dest, value);
            }
            SsaOp::Neg { dest, operand, .. } => {
                let value = self.get(*operand)?.wrapping_neg();
                self.set(*dest, value);
            }
            SsaOp::Not { dest, operand, .. } => {
                let value = !self.get(*operand)?;
                self.set(*dest, value);
            }
            SsaOp::Shl {
                dest,
                value,
                amount,
                ..
            } => {
                let shifted = match self.shift_count(*value, *amount)? {
                    Some(count) => self.read(*value, false)?.wrapping_shl(count),
                    None => 0,
                };
                self.set(*dest, shifted);
            }
            SsaOp::Shr {
                dest,
                value,
                amount,
                unsigned,
                ..
            } => {
                let shifted = match self.shift_count(*value, *amount)? {
                    Some(count) => self.read(*value, !*unsigned)?.wrapping_shr(count),
                    None => 0,
                };
                self.set(*dest, shifted);
            }
            SsaOp::Rem {
                dest,
                left,
                right,
                unsigned,
                ..
            } => {
                let divisor = self.read(*right, !*unsigned)?;
                let Some(value) = self.read(*left, !*unsigned)?.checked_rem(divisor) else {
                    return Ok(false);
                };
                self.set(*dest, value);
            }
            SsaOp::IntConv {
                dest,
                operand,
                target,
                unsigned,
                ..
            } => {
                let source_width = self.shape_of(*operand).0;
                let target_shape = shape(target);
                let value = self.get(*operand)?;
                let converted = if target_shape.0 <= source_width {
                    wrap(value, target_shape)
                } else {
                    wrap(wrap(value, (source_width, !*unsigned)), target_shape)
                };
                self.set(*dest, converted);
            }
            SsaOp::Ceq {
                dest, left, right, ..
            } => {
                let equal = self.read(*left, false)? == self.read(*right, false)?;
                self.set(*dest, i128::from(equal));
            }
            SsaOp::Clt {
                dest,
                left,
                right,
                unsigned,
                ..
            } => {
                let less = self.read(*left, !*unsigned)? < self.read(*right, !*unsigned)?;
                self.set(*dest, i128::from(less));
            }
            SsaOp::Cgt {
                dest,
                left,
                right,
                unsigned,
                ..
            } => {
                let greater = self.read(*left, !*unsigned)? > self.read(*right, !*unsigned)?;
                self.set(*dest, i128::from(greater));
            }
            other => return Err(format!("the oracle does not model {other:?}")),
        }
        Ok(true)
    }

    /// Decides a `BranchCmp` the way the machine does.
    fn compare(
        &self,
        left: SsaVarId,
        right: SsaVarId,
        cmp: CmpKind,
        unsigned: bool,
    ) -> Result<bool, String> {
        let signed = !unsigned && !matches!(cmp, CmpKind::Eq | CmpKind::Ne);
        let (l, r) = (self.read(left, signed)?, self.read(right, signed)?);
        Ok(match cmp {
            CmpKind::Eq => l == r,
            CmpKind::Ne => l != r,
            CmpKind::Lt => l < r,
            CmpKind::Le => l <= r,
            CmpKind::Gt => l > r,
            CmpKind::Ge => l >= r,
        })
    }
}

/// Blocks the oracle executes before it stops a run as non-terminating: past
/// a hundred trips of a byte-sized loop, a further trip visits no fold the
/// earlier ones did not.
const FUEL: usize = 300;

/// Runs `ssa` on one input and reports the first fold `verdicts` records that
/// the execution contradicts.
fn execute(
    ssa: &SsaFunction<MockTarget>,
    verdicts: &Verdicts,
    input: &[(SsaVarId, i128)],
    oversized: Oversized,
) -> Result<(), String> {
    let mut machine = Machine::new(ssa, oversized);
    for &(var, value) in input {
        machine.set(var, value);
    }
    let mut block_index = 0usize;
    let mut predecessor: Option<usize> = None;
    for _ in 0..FUEL {
        let block = ssa
            .block(block_index)
            .ok_or_else(|| format!("no block {block_index}"))?;
        if let Some(from) = predecessor {
            let mut incoming = Vec::new();
            for phi in block.phi_nodes() {
                let operand = phi
                    .operand_from(from)
                    .ok_or_else(|| format!("phi in b{block_index} has no operand from b{from}"))?;
                incoming.push((phi.result(), machine.get(operand.value())?));
            }
            for (result, value) in incoming {
                machine.set(result, value);
            }
        }
        let mut next = None;
        for instruction in block.instructions() {
            let op = instruction.op();
            let taken = match op {
                SsaOp::Return { .. } => return Ok(()),
                SsaOp::Jump { target } => {
                    next = Some(*target);
                    continue;
                }
                SsaOp::Branch {
                    condition,
                    true_target,
                    false_target,
                } => Some(if machine.get(*condition)? == 0 {
                    *false_target
                } else {
                    *true_target
                }),
                SsaOp::BranchCmp {
                    left,
                    right,
                    cmp,
                    unsigned,
                    true_target,
                    false_target,
                } => Some(if machine.compare(*left, *right, *cmp, *unsigned)? {
                    *true_target
                } else {
                    *false_target
                }),
                _ => None,
            };
            if let Some(target) = taken {
                if let Some(folded) = verdicts.branches.get(&block_index)
                    && *folded != target
                {
                    return Err(format!(
                        "b{block_index} was folded to b{folded} but the input {input:?} takes \
                         b{target} ({oversized:?} shifts)"
                    ));
                }
                next = Some(target);
                continue;
            }
            if !machine.step(op)? {
                return Ok(());
            }
            if let Some(dest) = op.dest()
                && let Some(folded) = verdicts.comparisons.get(&dest)
            {
                let actual = machine.get(dest)? != 0;
                if *folded != actual {
                    return Err(format!(
                        "{op:?} was folded to {folded} but the input {input:?} gives {actual} \
                         ({oversized:?} shifts)"
                    ));
                }
            }
        }
        let Some(target) = next else {
            return Err(format!("b{block_index} has no terminator"));
        };
        predecessor = Some(block_index);
        block_index = target;
    }
    Ok(())
}

/// Runs the pass on a copy of `ssa` and checks every fold it made against
/// execution on each input. Returns how many folds were checked.
fn folds_agree_with_execution(
    ssa: &SsaFunction<MockTarget>,
    inputs: &[Vec<(SsaVarId, i128)>],
) -> Result<usize, String> {
    let mut transformed = ssa.clone();
    assert!(
        ValueRangePropagationPass
            .run(
                &mut transformed,
                &PassEnv::new(&0u32, &NullListener, AnalysisContext::new(MACHINE))
                    .with_budget(budget(64))
            )
            .is_ok()
    );
    transformed
        .validate()
        .map_err(|errors| format!("the pass left invalid SSA: {errors:?}"))?;
    let verdicts = Verdicts::of(ssa, &transformed);
    // The two readings of an oversized shift only differ where there is one.
    let shifts = ssa.iter_blocks().any(|(_, block)| {
        block
            .instructions()
            .iter()
            .any(|instruction| matches!(instruction.op(), SsaOp::Shl { .. } | SsaOp::Shr { .. }))
    });
    let readings: &[Oversized] = if shifts {
        &[Oversized::Masked, Oversized::Zero]
    } else {
        &[Oversized::Masked]
    };
    for input in inputs {
        for &oversized in readings {
            execute(ssa, &verdicts, input, oversized)
                .map_err(|message| format!("{message}\n{ssa}"))?;
        }
    }
    Ok(verdicts.count())
}

/// Every value of one 8-bit input.
fn every_byte(var: SsaVarId) -> Vec<Vec<(SsaVarId, i128)>> {
    (0..=255i128).map(|value| vec![(var, value)]).collect()
}

/// A 64-bit add whose operand bound reaches `i64::MAX` wraps, so its sign is
/// not the sign of the unbounded sum.
///
/// `x & i64::MAX` is `[0, i64::MAX]`, and `+ 1` overflows the upper bound. The
/// interval `[1, +inf)` that comes out is not a 64-bit fact: at `x = -1` the
/// sum is `i64::MIN`, so `s < 0` is true there.
#[test]
fn a_64_bit_add_that_overflows_its_bound_proves_no_sign() {
    let mut b = Builder::new(1);
    let x = b.argument(0, MockType::I64);
    let mask = b.constant(0, MockType::I64, ConstValue::I64(i64::MAX));
    let masked = b.def(0, MockType::I64, |dest| SsaOp::And {
        dest,
        left: x,
        right: mask,
        flags: None,
    });
    let one = b.constant(0, MockType::I64, ConstValue::I64(1));
    let sum = b.def(0, MockType::I64, |dest| SsaOp::Add {
        dest,
        left: masked,
        right: one,
        flags: None,
    });
    let zero = b.constant(0, MockType::I64, ConstValue::I64(0));
    let negative = b.def(0, MockType::I64, |dest| SsaOp::Clt {
        dest,
        left: sum,
        right: zero,
        unsigned: false,
        signaling: false,
    });
    b.end(0, SsaOp::returns(Some(negative)));
    let ssa = b.finish();
    let inputs: Vec<_> = [-1i128, 0, 5, i128::from(i64::MAX)]
        .into_iter()
        .map(|value| vec![(x, value)])
        .collect();
    let checked = folds_agree_with_execution(&ssa, &inputs);
    assert!(checked.is_ok(), "{checked:?}");
}

