/// Builds `b0: c = x < 10; branch c ? b2 : b1; b1: jump b2; b2: return`, where
/// the edge `b0 -> b2` is critical.
#[test]
fn a_guard_does_not_refine_across_a_critical_edge() {
    let mut b = Builder::new(3);
    let x = b.argument(0, MockType::I32);
    let ten = b.constant(0, MockType::I32, ConstValue::I32(10));
    let below = b.def(0, MockType::I32, |dest| SsaOp::Clt {
        dest,
        left: x,
        right: ten,
        unsigned: false,
        signaling: false,
    });
    b.end(
        0,
        SsaOp::Branch {
            condition: below,
            true_target: 2,
            false_target: 1,
        },
    );
    b.end(1, SsaOp::Jump { target: 2 });
    b.end(2, SsaOp::returns(Some(x)));
    let ssa = b.finish();
    let cfg = SsaCfg::from_ssa(&ssa);
    let dominators = compute_dominators(&cfg, cfg.entry());
    let converged = analyze(&ssa, &budget(64), &BTreeMap::new());
    assert!(converged.is_ok());
    let Ok(ranges) = converged else { return };
    let at_join = ranges.range_at(&ssa, &dominators, x, 2);
    assert_eq!(
        at_join.max(),
        None,
        "b2 is also reached through b1, where x >= 10: {at_join:?}"
    );
    // The control: a block reached only through the false arm is refined.
    let false_arm = ranges.range_at(&ssa, &dominators, x, 1);
    assert_eq!(false_arm.min(), Some(10), "{false_arm:?}");
}

